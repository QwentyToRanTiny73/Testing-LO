export type Severity = 'ok' | 'watch' | 'risk';

export interface Branch {
  /** Что наблюдаете */
  when: string;
  /** Что это значит */
  means: string;
  /** Что делать */
  action: string;
  severity: Severity;
}

export interface Checkpoint {
  id: string;
  /** Контрольная точка ставится после этого модуля */
  afterModule: string;
  stage: string;
  title: string;
  /** Что должно сойтись, прежде чем идти дальше */
  gate: { label: string; value: string }[];
  /** Возможные варианты развития событий */
  branches: Branch[];
}

