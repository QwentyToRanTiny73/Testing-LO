export const REAGENTS: Reagent[] = [
  ...PUBLIC_REAGENTS.filter((p) => !privateReagents.some((r) => r.id === p.id)),
  ...privateReagents,
];

/** Оговорка к дозам, если её задаёт личный справочник */
export const REAGENTS_NOTE: string | undefined = privateReagentsNote;

export function getReagent(id: string): Reagent | undefined {
  return REAGENTS.find((r) => r.id === id);
}

