// Справочник препаратов симулятора — источник кликабельных сносок в этапах.
// Публичная часть — обезличенные позиции; личный справочник сезона добавляется
// только в закрытой сборке (SIM_PRIVATE=1).

import { privateReagents, privateReagentsNote } from 'sim-private';

export type ReagentCategory =
  | 'Дрожжи'
  | 'Питание и защита'
  | 'Ферменты'
  | 'Сульфитация'
  | 'Оклейка и стабилизация'
  | 'Танины'
  | 'Микробиология'
  | 'Дуб'
  | 'Кислоты';

export interface Reagent {
  id: string;
  name: string;
  category: ReagentCategory;
  /** Фасовка по закупочной ведомости сезона */
  pack?: string;
  /** Короткая роль — одна строка для чипа и заголовка */
  role: string;
  /** Рабочая доза по протоколу (ориентир) */
  dose?: string;
  /** Момент внесения */
  timing?: string;
  /** Разбивка по партиям сезона */
  lots?: string;
  /** Развёрнутое описание */
  description: string;
  /** Ограничения и несовместимости */
  cautions?: string[];
  /** Позиция присутствует в закупочной ведомости (фото) */
  photo?: boolean;
}

