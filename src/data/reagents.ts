  /** Короткая роль — одна строка для чипа и заголовка */
  role: string;
  /** Рабочая доза по протоколу (ориентир) */
  dose?: string;
  /** Момент внесения */
  timing?: string;
  /** Разбивка по партиям сезона */
  lots?: string;
  /** Развёрнутое описание */
