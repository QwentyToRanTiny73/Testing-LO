/**
 * Разбор числового поля калькулятора.
 *
 * Поля хранятся строками, чтобы очистка поля не подставляла ноль автоматически.
 * Здесь важно отличать «поле пустое» от «пользователь ввёл 0»: `parseFloat(v) || fallback`
 * подменяет законный ноль значением по умолчанию — например, мацерация при 0 °C
 * считалась бы как при 18 °C, а нулевой предел общего SO₂ — как 200 мг/л.
 */
export function num(v: string, fallback = 0): number {
  const n = parseFloat(v);
  return Number.isFinite(n) ? n : fallback;
}
